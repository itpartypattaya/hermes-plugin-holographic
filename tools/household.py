def entities(lang: str) -> dict[str, set[str]]:
    """fact key -> entity names in `lang` (named-person lookup per language)."""
    return {k: set(v[lang][1]) for k, v in FACTS.items()}


def named_extra(lang: str, query: str, keys, targets,
                ents: dict | None = None) -> list[str]:
    """Non-target output facts that mention a person named in the query:
    right-person extras and namesake facts. Substring matching is case-weak on
    ru (Андрей is not inside Андрея), so this column is descriptive — the
    measure is confusion() on static labels (the old probe looked facts up in
    the name map and always got nothing: PR #10 review, 2026-10-23)."""
    ents = entities(lang) if ents is None else ents
    qents = {e for es in ents.values() for e in es if e in query}
    return sorted({k for k in keys if k not in targets and ents.get(k, set()) & qents})


def confusion(q: dict, top5) -> list[str]:
    """Labelled wrong answers among the top five: static keys, so the count is
    language-independent (namesake or another person's same-attribute fact)."""
    return sorted(set(top5) & set(q.get("confused", ())))


def self_check() -> None:
    """Design-time invariants of the frozen set (recipe: labels must be right).

    - every target key exists; labels for noanswer are exactly [];
    - confused labels are known keys and never overlap targets;
    - en/ru/zh present for every record; one shared id => one shared split;
    - slice counts (dev 18/7/7/8, test 12/5/5/8) and chit (30/15);
    - nooverlap en: content words of the question do not appear in the target
      (stopword list below; the en check is the design check — ru/zh are
      semantic translations and are not tokenized here).
    """
    stop = set("""a an the to of for and or in on at by with from as is are was
    were be been do does did done have has had he she it they his her its my your
    our their this that these those i you we not no yes but if then than so what
    when where how which who whom why would will can could may might shall should
    there here just very too also any all some one two get got make made go went
    take took come came say said\n    after before until during over under between without within against around about into""".split())

    def toks(s: str) -> set[str]:
        return {w for w in "".join(c.lower() if c.isalnum() else " " for c in s).split()
                if w.strip("s") not in stop and w not in stop}

    errs = []
    keys = set(FACTS)
    for qid, q in QUERIES.items():
        for lang in LANGS:
            if not q.get(lang):
                errs.append(f"{qid}: no {lang} text")
        if not all(t in keys for t in q["targets"]):
            errs.append(f"{qid}: unknown target")
        if (q["slice"] == "noanswer") != (q["targets"] == []):
            errs.append(f"{qid}: noanswer label mismatch")
        conf = set(q.get("confused", []))
        if not conf <= keys:
            errs.append(f"{qid}: unknown confused {sorted(conf - keys)}")
        if conf & set(q["targets"]):
            errs.append(f"{qid}: confused overlaps targets")
    splits = {q["split"] for q in QUERIES.values()}
    if splits != {"dev", "test"}:
        errs.append(f"bad splits {splits}")
    want = {("dev", "plain"): 18, ("dev", "multi"): 7, ("dev", "noanswer"): 7,
            ("dev", "nooverlap"): 8, ("test", "plain"): 12, ("test", "multi"): 5,
            ("test", "noanswer"): 5, ("test", "nooverlap"): 8}
    got: dict[tuple, int] = {}
    for q in QUERIES.values():
        got[(q["split"], q["slice"])] = got.get((q["split"], q["slice"]), 0) + 1
    if got != want:
        errs.append(f"slice counts {got} != {want}")
    chit = {"dev": 0, "test": 0}
    for hid, h in CHITCHAT.items():
        for lang in LANGS:
            if not h.get(lang):
                errs.append(f"{hid}: no {lang} text")
        chit[h["split"]] += 1
    if chit != {"dev": 30, "test": 15}:
        errs.append(f"chit counts {chit}")
    # nooverlap en
    for qid, q in QUERIES.items():
        if q["slice"] != "nooverlap":
            continue
        qt = toks(q["en"])
        for t in q["targets"]:
            ov = qt & toks(FACTS[t]["en"][0])
            if ov:
                errs.append(f"{qid}: nooverlap words {sorted(ov)} vs {t}")
    if errs:
        raise SystemExit("household self_check FAILED:\n  " + "\n  ".join(errs))
    print(f"household self_check OK: {len(FACTS)} facts, {len(QUERIES)} questions "
          f"(dev {sum(1 for q in QUERIES.values() if q['split']=='dev')}, "
          f"test {sum(1 for q in QUERIES.values() if q['split']=='test')}), "
          f"{len(CHITCHAT)} chit")


if __name__ == "__main__":
    self_check()

